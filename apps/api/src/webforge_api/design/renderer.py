def illustration(brief: DesignBrief, seed: str) -> str:
    """An original, deterministic abstract SVG in the brief's palette (decorative)."""
    pal = brief.palette
    h = hashlib.sha256(seed.encode()).digest()
    cx1, cy1, r1 = 60 + h[0] % 200, 40 + h[1] % 140, 40 + h[2] % 60
    cx2, cy2, r2 = 120 + h[3] % 160, 80 + h[4] % 120, 30 + h[5] % 50
    x3, y3, w3 = 20 + h[6] % 120, 120 + h[7] % 60, 120 + h[8] % 140
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 240" role="presentation" aria-hidden="true" focusable="false">'
        f'<rect width="320" height="240" fill="{pal.surface}"/>'
        f'<circle cx="{cx1}" cy="{cy1}" r="{r1}" fill="{pal.primary}" opacity="0.85"/>'
        f'<circle cx="{cx2}" cy="{cy2}" r="{r2}" fill="{pal.accent}" opacity="0.8"/>'
        f'<rect x="{x3}" y="{y3}" width="{w3}" height="36" rx="18" fill="{pal.secondary}" opacity="0.9"/>'
        "</svg>"
    )


SCAN_RULES = [
    ("script", re.compile(r"<\s*script", re.I)),
    ("event_handler", re.compile(r"<[^>]+\son[a-z]+\s*=", re.I)),
    ("javascript_url", re.compile(r"javascript\s*:", re.I)),
    ("external_url", re.compile(r"""(?:href|src|action|formaction|poster|srcset)\s*=\s*["']?\s*(?:[a-z][a-z0-9+.-]*:|//)""", re.I)),
    ("embedded_content", re.compile(r"<\s*(iframe|object|embed|frame|link|base|meta\s+http-equiv=.refresh)", re.I)),
    ("css_fetch", re.compile(r"@import|url\s*\(", re.I)),
    ("form_action", re.compile(r"<form[^>]*\saction\s*=", re.I)),
    ("named_field", re.compile(r"<(input|textarea|select)[^>]*\sname\s*=", re.I)),
    ("submit_button", re.compile(r"<button(?![^>]*type=\"button\")[^>]*>", re.I)),
]  # fmt: skip


def scan_page(html: str) -> list[dict[str, str]]:
    issues = [
        {"code": code, "detail": "Rendered page failed safety scan"}
        for code, rule in SCAN_RULES
        if rule.search(html)
    ]
    if NOTICE not in html:
        issues.append({"code": "missing_notice", "detail": "Concept notice is missing"})
    if len(html.encode()) > MAX_PAGE_BYTES:
        issues.append({"code": "too_large", "detail": f"Page exceeds {MAX_PAGE_BYTES} bytes"})
    return issues


def render_site(
    brief: DesignBrief,
    facts: list[dict[str, Any]],
    *,
    industry: str | None,
    author_name: str,
    author_url: str,
) -> RenderedSite:
    by_field = {f["field"]: str(f["value"]) for f in facts}
    wordmark = by_field.get("business_name") or "Your Business"
    variant = variant_for(industry)
    css = build_css(brief, variant)
    svg = illustration(brief, wordmark)
    contact = [
        {"label": label, "value": by_field[k]}
        for k, label in CONTACT_FIELDS.items()
        if by_field.get(k)
    ]
    pages = sorted(brief.pages, key=lambda p: PAGE_ORDER[p.slug])
    nav = [{"slug": p.slug, "title": p.title} for p in pages]
    template = _env.get_template("page")
    out: dict[str, bytes] = {}
    issues: list[dict[str, str]] = []
    for page in pages:
        html = template.render(
            page=page, nav=nav, wordmark=wordmark, variant=variant, css=css, notice=NOTICE,
            author_name=author_name, author_url=author_url,
            ctx={"illustration": Markup(svg), "contact_facts": contact},  # noqa: S704 - generated from validated hex
        )  # fmt: skip
        for issue in scan_page(html):
            issues.append({**issue, "page": page.slug})
        out[page.slug] = html.encode()
    return RenderedSite(variant, out, {p.slug: p.title for p in pages}, svg.encode(), issues)
