"""Render approved briefs into versioned six-page concepts; review, activation and rollback."""

from __future__ import annotations

import hashlib
import uuid
from dataclasses import dataclass
from datetime import datetime
from typing import Any

from sqlalchemy import func, select, update
from sqlalchemy.orm import Session

from webforge_api.config import Settings
from webforge_api.design.brief_schema import DesignBrief as BriefModel
from webforge_api.design.integrity import check_brief
from webforge_api.design.renderer import RENDERER_VERSION, render_site
from webforge_api.models import (
    Asset,
    DesignBrief,
    DesignPage,
    DesignProject,
    DesignRender,
    Prospect,
)
from webforge_api.models.enums import RunStatus
from webforge_api.security.crypto import Crypto
from webforge_api.services import activity
from webforge_api.services.context import RequestMeta
from webforge_api.services.errors import ConflictError, NotFoundError
from webforge_api.services.jobs import JobError, JobSpec
from webforge_api.services.prospect_state import LOCKED
from webforge_api.storage import Storage

RENDER = JobSpec("design.render", "design", max_attempts=2)


@dataclass
class RenderDeps:
    db: Session
    settings: Settings
    crypto: Crypto
    storage: Storage
    now: datetime


def latest_approved_brief(db: Session, project_id: uuid.UUID) -> DesignBrief | None:
    return db.scalar(
        select(DesignBrief)
        .where(DesignBrief.design_project_id == project_id, DesignBrief.status == "APPROVED")
        .order_by(DesignBrief.version.desc())
        .limit(1)
    )


def render_project(
    deps: RenderDeps, project_id: uuid.UUID, actor_user_id: uuid.UUID | None = None
) -> DesignRender:
    db, now = deps.db, deps.now
    project = db.get(DesignProject, project_id, with_for_update=True)
    if project is None:
        raise JobError("not_found", "Design project not found.")
    prospect = db.get(Prospect, project.prospect_id)
    if prospect is None or prospect.state in LOCKED or prospect.do_not_contact:
        raise JobError("prospect_locked", "Prospect is locked; not rendering.")
    brief_row = latest_approved_brief(db, project.id)
    if brief_row is None or brief_row.brief is None:
        raise JobError("no_approved_brief", "Approve a brief before rendering.")
    brief = BriefModel.model_validate(brief_row.brief)  # re-validate stored JSON (defence in depth)
    facts: list[dict[str, Any]] = list(brief_row.facts_snapshot.get("facts", []))
    issues: list[dict[str, str]] = [
        {"code": i.code, "detail": i.detail, "page": i.location}
        for i in check_brief(brief, {str(f["id"]): str(f["value"]) for f in facts})
    ]
    site = render_site(brief, facts, industry=prospect.industry,
                       author_name=deps.settings.concept_author_name, author_url=deps.settings.concept_author_url)  # fmt: skip
    issues += site.issues
    version = (
        db.scalar(
            select(func.max(DesignRender.version)).where(
                DesignRender.design_project_id == project.id
            )
        )
        or 0
    ) + 1
    prefix = f"designs/{project.id}/r{version}"
    pages: list[dict[str, Any]] = []
    if not issues:
        for order, (slug, html) in enumerate(site.pages.items()):
            stored = deps.storage.put(f"{prefix}/{slug}.html", html, "text/html; charset=utf-8")
            pages.append(
                {
                    "slug": slug,
                    "title": site.titles[slug],
                    "key": stored.key,
                    "sha256": stored.sha256,
                    "bytes": stored.size,
                }
            )
            db.add(DesignPage(design_project_id=project.id, slug=slug, title=site.titles[slug], page_type=slug,
                              content={"html_key": stored.key, "sha256": stored.sha256, "render_version": version},
                              render_status=RunStatus.SUCCEEDED, sort_order=order, version=version))  # fmt: skip
        art = deps.storage.put(f"{prefix}/illustration.svg", site.illustration_svg, "image/svg+xml")
        asset = Asset(storage_key=art.key, asset_type="illustration", mime_type="image/svg+xml", size_bytes=art.size,
                      sha256=art.sha256, provider="webforge-renderer", license_id="original-generated",
                      attribution_required=False,
                      attribution_text="Original abstract illustration generated by the concept renderer.")  # fmt: skip
        db.add(asset)
        db.flush()
        assets = [
            {
                "id": str(asset.id),
                "key": art.key,
                "license": "original-generated",
                "sha256": art.sha256,
            }
        ]
    else:
        assets = []
    digest = hashlib.sha256(b"".join(site.pages[s] for s in sorted(site.pages))).hexdigest()
    row = DesignRender(
        design_project_id=project.id, brief_id=brief_row.id, version=version, renderer_version=RENDERER_VERSION,
        status="FAILED" if issues else "RENDERED", variant=site.variant, scan_issues=issues, created_at=now,
        manifest={"pages": pages, "assets": assets, "brief_version": brief_row.version, "site_sha256": digest,
                  "fonts": "system font stacks only (no downloads)"},
    )  # fmt: skip
    db.add(row)
    project.renderer_version = RENDERER_VERSION
    project.design_tokens = {
        "palette": brief.palette.model_dump(),
        "typography": brief.typography.model_dump(),
        "variant": site.variant,
    }
    project.page_plan = {"pages": [{"slug": p["slug"], "title": p["title"]} for p in pages]}
    db.flush()
    activity.record(db, deps.crypto, action="design.rendered", actor_user_id=actor_user_id, system=actor_user_id is None,
                    entity_type="design_render", entity_id=row.id,
                    metadata={"version": version, "status": row.status, "issues": len(issues)})  # fmt: skip
    db.commit()
    return row


def _get(db: Session, render_id: uuid.UUID) -> DesignRender:
    row = db.get(DesignRender, render_id, with_for_update=True)
    if row is None:
        raise NotFoundError("not_found", "Render not found.")
    return row


def _activate(db: Session, row: DesignRender) -> None:
    db.execute(update(DesignRender).where(DesignRender.design_project_id == row.design_project_id,
                                          DesignRender.id != row.id).values(is_active=False))  # fmt: skip
    db.flush()
    row.is_active = True


def review_render(db: Session, crypto: Crypto, *, render_id: uuid.UUID, approve: bool, notes: str,
                  actor_user_id: uuid.UUID, now: datetime, meta: RequestMeta) -> DesignRender:  # fmt: skip
    row = _get(db, render_id)
    if row.status != "RENDERED":
        raise ConflictError(
            "not_reviewable", f"Render is {row.status}; only new renders can be reviewed."
        )
    row.status = "APPROVED" if approve else "REJECTED"
    row.review_notes, row.reviewed_by_user_id, row.reviewed_at = notes[:2000], actor_user_id, now
    if approve:
        _activate(db, row)
    activity.record(db, crypto, action="design.render_approved" if approve else "design.render_rejected",
                    actor_user_id=actor_user_id, meta=meta, entity_type="design_render", entity_id=row.id,
                    metadata={"version": row.version})  # fmt: skip
    db.commit()
    return row


def activate_render(
    db: Session,
    crypto: Crypto,
    *,
    render_id: uuid.UUID,
    actor_user_id: uuid.UUID,
    meta: RequestMeta,
) -> DesignRender:
    """Rollback/forward: make an earlier approved render the active one."""
    row = _get(db, render_id)
    if row.status != "APPROVED":
        raise ConflictError("not_approved", "Only approved renders can be made active.")
    _activate(db, row)
    activity.record(db, crypto, action="design.render_activated", actor_user_id=actor_user_id, meta=meta,
                    entity_type="design_render", entity_id=row.id, metadata={"version": row.version})  # fmt: skip
    db.commit()
    return row


def page_html(db: Session, storage: Storage, render_id: uuid.UUID, slug: str) -> bytes:
    row = db.get(DesignRender, render_id)
    page = next(
        (p for p in (row.manifest.get("pages", []) if row else []) if p["slug"] == slug), None
    )
    if row is None or page is None:
        raise NotFoundError("not_found", "Page not found.")
    data = storage.get(page["key"])
    if hashlib.sha256(data).hexdigest() != page["sha256"]:
        raise ConflictError("integrity_mismatch", "Stored page does not match its recorded hash.")
    return data
