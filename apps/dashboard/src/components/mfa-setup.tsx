"use client";

import { useRouter } from "next/navigation";
import { useState, type FormEvent } from "react";

import { RecoveryCodes } from "@/components/recovery-codes";
import { Alert, Button, Field } from "@/components/ui";
import { api } from "@/lib/api-client";
import { pathForState, type AuthResponse } from "@/lib/auth-shared";

interface Setup {
  secret: string;
  otpauth_uri: string;
  qr_svg_data_uri: string;
}

export function MfaSetup({ doneHref = "/" }: { doneHref?: string }) {
  const router = useRouter();
  const [setup, setSetup] = useState<Setup | null>(null);
  const [codes, setCodes] = useState<string[] | null>(null);
  const [nextPath, setNextPath] = useState(doneHref);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function start() {
    setBusy(true);
    setError(null);
    const result = await api<Setup>("/auth/mfa/setup", "POST");
    setBusy(false);
    if (result.ok) setSetup(result.data);
    else setError(result.error.message);
  }

  async function enable(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const code = String(new FormData(event.currentTarget).get("code") ?? "");
    setBusy(true);
    setError(null);
    const result = await api<AuthResponse & { recovery_codes: string[] }>("/auth/mfa/enable", "POST", {
      code,
    });
    setBusy(false);
    if (!result.ok) {
      setError(result.error.message);
      return;
    }
    setCodes(result.data.recovery_codes);
    setNextPath(pathForState(result.data.session.state) ?? doneHref);
  }

  if (codes) {
    return (
      <div className="grid gap-4">
        <Alert tone="success">Two-factor authentication is on.</Alert>
        <RecoveryCodes codes={codes} />
        <Button
          type="button"
          onClick={() => {
            router.replace(nextPath);
            router.refresh();
          }}
        >
          I have saved my codes
        </Button>
      </div>
    );
  }

  if (!setup) {
    return (
      <div className="grid gap-4">
        {error && <Alert>{error}</Alert>}
        <p className="text-sm text-muted">
          You will need an authenticator app such as 1Password, Bitwarden, Google Authenticator or Microsoft
          Authenticator.
        </p>
        <Button type="button" onClick={start} busy={busy}>
          Start setup
        </Button>
      </div>
    );
  }

  return (
    <form onSubmit={enable} className="grid gap-4" noValidate>
      {error && <Alert>{error}</Alert>}
      <p className="text-sm">1. Scan this QR code with your authenticator app.</p>
      {/* eslint-disable-next-line @next/next/no-img-element -- inline data URI generated by the API */}
      <img
        src={setup.qr_svg_data_uri}
        alt="QR code for your authenticator app"
        width={200}
        height={200}
        className="mx-auto rounded-lg bg-white p-2"
      />
      <details className="text-sm">
        <summary className="cursor-pointer text-accent">Can’t scan? Enter the key manually</summary>
        <code className="mt-2 block break-all rounded bg-background p-2 font-mono text-xs">
          {setup.secret}
        </code>
      </details>
      <Field
        id="code"
        name="code"
        label="2. Enter the 6-digit code it shows"
        inputMode="numeric"
        autoComplete="one-time-code"
        maxLength={6}
        required
      />
      <Button type="submit" busy={busy}>
        Turn on two-factor authentication
      </Button>
    </form>
  );
}
